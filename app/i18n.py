SUPPORTED = set(TRANSLATIONS.keys())


def detect_language(request: Request, user=None) -> str:
    if user and getattr(user, "language_code", None) in SUPPORTED:
        return user.language_code
    cookie = request.cookies.get("lang")
    if cookie in SUPPORTED:
        return cookie
    accept = request.headers.get("accept-language", "")
    if accept.lower().startswith("pt"):
        return "pt-BR"
    return "en"


def get_translator(lang: str):
    strings = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    fallback = TRANSLATIONS["en"]

    def _(key: str, **kwargs: str) -> str:
        s = strings.get(key, fallback.get(key, key))
        for k, v in kwargs.items():
            s = s.replace(f"{{{k}}}", v)
        return s

    return _
